// Exports the customer data-retention matrix as a reviewable Markdown table.
//
// The matrix itself lives in the CODE (`src/lib/customers/anonymize.ts`); this
// script only RENDERS it for a legal/accounting reviewer, and adds the
// column's data type from the Prisma schema so the reviewer sees the real
// field, not a paraphrase.
//
//   node scripts/export-retention-matrix.mjs
//
// Read-only: it reads two files and writes nothing.
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

const ROOT = resolve(process.cwd());
const matrixSource = readFileSync(resolve(ROOT, "src/lib/customers/anonymize.ts"), "utf8");
const schema = readFileSync(resolve(ROOT, "prisma/schema.prisma"), "utf8");

/** The matrix entries, parsed from the source of truth. */
function entries() {
  const start = matrixSource.indexOf("export const CUSTOMER_DATA_RETENTION_MATRIX");
  const end = matrixSource.indexOf("\n];", start);
  const block = matrixSource.slice(start, end);
  const rows = [];
  const re = /\{\s*location:\s*"([^"]+)"[\s\S]*?label:\s*"([^"]+)"[\s\S]*?action:\s*"([^"]+)"[\s\S]*?reason:\s*"([^"]+)"([\s\S]*?)\}/g;
  for (const match of block.matchAll(re)) {
    const tail = match[5] ?? "";
    rows.push({
      location: match[1],
      label: match[2],
      action: match[3],
      reason: match[4],
      restricted: /restricted:\s*true/.test(tail),
      accessScope: (tail.match(/accessScope:\s*"([^"]+)"/) ?? [])[1] ?? null,
      requiredPermission: (tail.match(/requiredPermission:\s*"([^"]+)"/) ?? [])[1] ?? null,
    });
  }
  return rows;
}

/** The Prisma type of a column, from the schema (matched by field name or @map). */
function columnType(location) {
  const table = location.split(".")[0];
  const column = location.split(".").slice(1).join(".").replace(/\s*\(.*\)$/, "");
  // The Prisma model is singular; the table name is in @@map("…").
  const models = [...schema.matchAll(/model\s+(\w+)\s+\{[\s\S]*?\n\}/g)];
  const model = models.find((match) => match[0].includes(`@@map("${table}")`));
  if (!model) return null;
  const field = model[0]
    .split("\n")
    .map((line) => line.trim())
    .find((line) => {
      if (!line || line.startsWith("//") || line.startsWith("@@")) return false;
      const name = line.split(/\s+/)[0];
      const mapped = (line.match(/@map\("([^"]+)"\)/) ?? [])[1];
      return name === column || mapped === column;
    });
  if (!field) return null;
  const type = field.split(/\s+/)[1] ?? "";
  return type.replace(/\?$/, "").trim();
}

/** The approval status of an entry, from its own classification. */
function approvalStatus(entry) {
  if (entry.action === "LEGAL_REVIEW_REQUIRED") return "LEGAL-REVIEW-REQUIRED";
  if (entry.restricted) return "LEGAL-REVIEW-REQUIRED (restricted access)";
  return "PENDING-OWNER-REVIEW (technical implementation complete)";
}

const rows = entries();
console.log(`# CUSTOMER_DATA_RETENTION_MATRIX — ${rows.length} entries (generated)\n`);
console.log("| # | Table | Column | Type | Copy | Action | Reason | Impact on orders/reports | Access permission | Approval |");
console.log("|---|-------|--------|------|------|--------|--------|----------------------------|------------------|----------|");
rows.forEach((entry, index) => {
  const [table, column] = entry.location.split(".");
  const type = columnType(entry.location) ?? "—";
  const impact =
    entry.action === "RETAIN_OPERATIONAL"
      ? "لا يمسّ الطلبات ولا التقارير"
      : entry.action === "REMOVE"
        ? "يزيل البيانات من الطلب/السجل بلا تغيير قيمه المالية"
        : entry.action === "REPLACE"
          ? "يستبدل القيمة فقط — القيم المالية لا تتغير"
          : entry.action === "LEGAL_REVIEW_REQUIRED"
            ? "خارج نطاق التطبيق — قرار منفصل"
            : "—";
  const access = entry.requiredPermission ?? "—";
  console.log(
    `| ${index + 1} | ${table} | ${column} | ${type} | ${entry.location} | \`${entry.action}\` | ${entry.reason} | ${impact} | ${access} | ${approvalStatus(entry)} |`,
  );
});
console.log("\n> Generated by `node scripts/export-retention-matrix.mjs` — read-only, nothing is written.");
