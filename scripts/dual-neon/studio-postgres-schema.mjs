import { quote } from "./sqlite-snapshot.mjs";

const searchTables = new Set(["products_fts", "products_effective_fts"]);

export function postgresSchema(inventory) {
  const beforeImport = ["CREATE SCHEMA studio", "SET LOCAL search_path TO studio, pg_catalog"];
  const afterImport = [];
  const mappings = [];
  // Delay foreign keys until all tables have been loaded, then validate them against the imported data.
  for (const entry of inventory.schema) {
    if (entry.kind === "table") {
      if (/\b(?:COLLATE|WITHOUT ROWID|STRICT)\b/i.test(entry.sql)) throw new Error("Unsupported SQLite table: " + entry.name);
      const sql = entry.sql
        .replace(/\bINTEGER PRIMARY KEY AUTOINCREMENT\b/g, "bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
        .replace(/\bINTEGER\b/g, "bigint")
        .replace(/ REFERENCES \w+\(\w+\)(?: ON DELETE (?:RESTRICT|CASCADE))?/g, "");
      beforeImport.push(sql);
      const foreignKeys = inventory.tables[entry.name].foreignKeys;
      for (const key of foreignKeys) {
        if (key.seq !== 0 || !["NO ACTION", "CASCADE", "RESTRICT"].includes(key.on_delete) || key.on_update !== "NO ACTION") {
          throw new Error("Unsupported foreign key: " + entry.name);
        }
        afterImport.push(`ALTER TABLE ${quote(entry.name)} ADD FOREIGN KEY (${quote(key.from)})
          REFERENCES ${quote(key.table)} (${quote(key.to)}) ON DELETE ${key.on_delete}`);
      }
      mappings.push({ source: entry.name, target: "studio." + entry.name, strategy: "copy exact values" });
    } else if (entry.kind === "virtual") {
      if (!searchTables.has(entry.name)) throw new Error("Unknown virtual table: " + entry.name);
      const name = quote(entry.name);
      beforeImport.push(`CREATE TABLE ${name} (
        product_id text PRIMARY KEY, name text, codes text,
        search_document tsvector GENERATED ALWAYS AS (
          to_tsvector('pg_catalog.simple', coalesce(name, '') || ' ' || coalesce(codes, ''))
        ) STORED
      )`);
      afterImport.push(`CREATE INDEX ON ${name} USING gin (search_document)`);
      mappings.push({ source: entry.name, target: "studio." + entry.name, strategy: "copy normalized tokens and generate GIN search index" });
    } else if (entry.kind === "shadow") {
      mappings.push({ source: entry.name, target: null, strategy: "SQLite FTS internals regenerated by PostgreSQL" });
    } else if (entry.kind === "view" || entry.kind === "index") {
      afterImport.push(entry.sql.replace("name_effective COLLATE NOCASE", '(lower(name_effective) COLLATE "C")'));
      mappings.push({ source: entry.name, target: "studio." + entry.name, strategy: "recreate" });
    } else if (entry.kind === "trigger") {
      afterImport.push(...compileTrigger(entry));
      mappings.push({ source: entry.name, target: "studio." + entry.name, strategy: "recreate with PL/pgSQL" });
    } else {
      throw new Error("Unmapped SQLite object: " + entry.name);
    }
  }
  afterImport.push(`CREATE FUNCTION reject_immutable_change() RETURNS trigger
    LANGUAGE plpgsql SET search_path TO pg_catalog AS $$
    BEGIN RAISE EXCEPTION USING MESSAGE = 'immutable Studio records', ERRCODE = '23514'; END; $$`);
  afterImport.push(`CREATE TRIGGER protect_v0 BEFORE UPDATE OR DELETE ON catalog_versions FOR EACH ROW
    WHEN (OLD.id = 'f2f03aad-261d-4596-bede-5d1a8a6f14cb') EXECUTE FUNCTION reject_immutable_change()`);
  afterImport.push(`CREATE TRIGGER protect_release_receipt BEFORE DELETE ON release_receipts
    FOR EACH ROW EXECUTE FUNCTION reject_immutable_change()`);
  for (const table of ["catalog_versions", "version_items", "edit_journal", "review_events",
    "review_checkpoints", "catalog_releases", "release_snapshots", "release_receipts"]) {
    afterImport.push(`CREATE TRIGGER protect_truncate BEFORE TRUNCATE ON ${quote(table)}
      FOR EACH STATEMENT EXECUTE FUNCTION reject_immutable_change()`);
  }
  return { beforeImport, afterImport, mappings };
}

function compileTrigger(entry) {
  const match = /^CREATE TRIGGER\s+\w+\s+(BEFORE .+? ON \w+)(?:\s+WHEN\s+([\s\S]+?))?\s+BEGIN\s+SELECT RAISE\(ABORT, ('[^']*')\);\s*END$/i.exec(entry.sql);
  if (!match) throw new Error("Unsupported SQLite trigger: " + entry.name);
  const [, event, sqliteCondition, message] = match;
  const name = quote(entry.name);
  const reject = `RAISE EXCEPTION USING MESSAGE = ${message}, ERRCODE = '23514';`;
  const body = sqliteCondition
    ? `IF ${sqliteCondition.replace("j.new_value IS NEW.value", "j.new_value IS NOT DISTINCT FROM NEW.value")}
       THEN ${reject} END IF; RETURN NEW;`
    : reject;
  return [
    `CREATE FUNCTION ${name}() RETURNS trigger LANGUAGE plpgsql
     SET search_path TO studio, pg_catalog AS $trigger$ BEGIN ${body} END; $trigger$`,
    `CREATE TRIGGER ${name} ${event} FOR EACH ROW EXECUTE FUNCTION ${name}()`,
  ];
}
